#!/usr/bin/env node
// Generate src/migrations.generated.ts by scanning the workspace
// `packages/{identity,vault,mail}/migrations/*.sql` directories. The output
// contains every SQL file inlined as a JS string literal plus its SHA-256
// checksum, so the Worker bundle is fully self-contained at runtime.
//
// Re-run on every typecheck/build/deploy via package.json prescripts.

import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const APP_DIR = join(HERE, '..')
const REPO_ROOT = join(APP_DIR, '..', '..')

const SOURCES = [
  { name: 'identityMigrations', dir: join(REPO_ROOT, 'packages/identity/migrations') },
  { name: 'vaultMigrations', dir: join(REPO_ROOT, 'packages/vault/migrations') },
  { name: 'mailMigrations', dir: join(REPO_ROOT, 'packages/mail/migrations') },
]

function loadDir(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((filename) => {
      const path = join(dir, filename)
      const sql = readFileSync(path, 'utf8')
      const checksum = `sha256-${createHash('sha256').update(sql).digest('hex')}`
      return { filename, checksum, sql }
    })
}

const parts = SOURCES.map(({ name, dir }) => {
  const entries = loadDir(dir)
  const body = entries
    .map(
      (e) =>
        `  {\n    filename: ${JSON.stringify(e.filename)},\n    checksum: ${JSON.stringify(
          e.checksum,
        )},\n    sql: ${JSON.stringify(e.sql)},\n  },`,
    )
    .join('\n')
  return { name, dir, count: entries.length, body }
})

const banner = `// AUTO-GENERATED by apps/migrator/scripts/build-migrations.mjs — do not edit by hand.
// Sources:
${SOURCES.map(({ dir }) => `//   ${relative(REPO_ROOT, dir)}`).join('\n')}
`

const out = `${banner}
export type Migration = {
  filename: string
  /** sha256-<hex> over the file's UTF-8 bytes. Stored in _migrations so a
   *  drifted file fails fast instead of silently re-applying. */
  checksum: string
  sql: string
}

${parts
  .map(
    ({ name, body }) =>
      `export const ${name}: readonly Migration[] = [\n${body}\n] as const`,
  )
  .join('\n\n')}
`

const target = join(APP_DIR, 'src/migrations.generated.ts')
writeFileSync(target, out)

console.log(
  `wrote ${relative(REPO_ROOT, target)} (${parts
    .map((p) => `${p.name.replace('Migrations', '')}=${p.count}`)
    .join(', ')})`,
)
