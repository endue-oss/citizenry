#!/usr/bin/env node
// Reads `*/errors.tsp` and emits matching TS constants under
// `generated/error-codes/{service}.ts`. Consumers (packages/identity,
// packages/vault, apps/api, ...) import these instead of inlining the
// `"ERR-…-…"` literals so the catalog and the code can't drift apart.
//
// Why a tiny hand-rolled parser: the .tsp enum block is regular —
// `enum NAME { key: "VALUE", … }` with optional JSDoc lines above each
// entry. Pulling in @typespec/compiler just to read literals is overkill
// and would couple this generator to the compiler's API surface.

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = dirname(fileURLToPath(import.meta.url)) // .../packages/spec/scripts
const SPEC_ROOT = join(ROOT, '..')
const OUT_DIR = join(SPEC_ROOT, 'generated', 'error-codes')

// service slug → tsp source path. Add a new line per service.
const SOURCES = [
  { slug: 'identity', tsp: 'identity/errors.tsp', enumName: 'IdentityErrorCode' },
  { slug: 'mail', tsp: 'mail/errors.tsp', enumName: 'MailErrorCode' },
  { slug: 'vault', tsp: 'vault/errors.tsp', enumName: 'VaultErrorCode' },
]

/**
 * Parse one `enum Name { … }` block and return ordered entries.
 *   `[{ key, value, doc }, …]`
 *
 * The block grammar we accept (mirrors what `errors.tsp` actually uses):
 *
 *   /** doc *\/  // optional, one or multiple lines
 *   key_snake: "STRING",
 */
function parseEnum(source, enumName) {
  const enumStart = source.indexOf(`enum ${enumName}`)
  if (enumStart < 0) throw new Error(`enum ${enumName} not found`)
  const braceOpen = source.indexOf('{', enumStart)
  if (braceOpen < 0) throw new Error(`enum ${enumName}: no opening brace`)
  // Find matching close — enum bodies don't nest braces.
  const braceClose = source.indexOf('}', braceOpen)
  if (braceClose < 0) throw new Error(`enum ${enumName}: no closing brace`)
  const body = source.slice(braceOpen + 1, braceClose)

  const entries = []
  // Pending JSDoc captured across lines until the next entry consumes it.
  let pendingDoc = []
  let inBlockDoc = false

  for (const rawLine of body.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (line.length === 0) continue

    // Block JSDoc: /** … */ possibly spanning multiple lines.
    if (line.startsWith('/**')) {
      inBlockDoc = true
      const closed = line.includes('*/')
      const stripped = line
        .replace(/^\/\*\*\s?/, '')
        .replace(/\s?\*\/\s*$/, '')
        .replace(/^\*\s?/, '')
        .trim()
      if (stripped) pendingDoc.push(stripped)
      if (closed) inBlockDoc = false
      continue
    }
    if (inBlockDoc) {
      const stripped = line.replace(/^\*\s?/, '').replace(/\s?\*\/\s*$/, '').trim()
      if (line.includes('*/')) inBlockDoc = false
      if (stripped) pendingDoc.push(stripped)
      continue
    }

    // Section comments (`// ── 0xxx …`) are dropped — they're meaningful
    // in the .tsp but the generated TS gets its own structure.
    if (line.startsWith('//')) continue

    // Entry: `key: "VALUE",`
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*"([^"]+)"\s*,?\s*$/)
    if (!m) continue
    const [, key, value] = m
    entries.push({ key, value, doc: pendingDoc.join(' ').trim() })
    pendingDoc = []
  }
  return entries
}

function emitTs({ slug, enumName, entries }) {
  const constName = `${slug.toUpperCase()}_ERR`
  const keyType = `${capitalize(slug)}ErrorCodeKey`
  const valueType = `${capitalize(slug)}ErrorCodeValue`

  const lines = []
  lines.push(`// AUTO-GENERATED by packages/spec/scripts/gen-error-codes.mjs`)
  lines.push(`// Source of truth: packages/spec/${slug}/errors.tsp (enum ${enumName})`)
  lines.push(`// Do not edit by hand — re-run \`pnpm --filter @citizenry/spec build\` instead.`)
  lines.push(``)
  lines.push(`export const ${constName} = {`)
  for (const e of entries) {
    if (e.doc) lines.push(`  /** ${escapeBlockComment(e.doc)} */`)
    lines.push(`  ${e.key}: '${e.value}',`)
  }
  lines.push(`} as const`)
  lines.push(``)
  lines.push(`export type ${keyType} = keyof typeof ${constName}`)
  lines.push(`export type ${valueType} = (typeof ${constName})[${keyType}]`)
  lines.push(``)
  return lines.join('\n')
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

function escapeBlockComment(s) {
  // Prevent `*/` from prematurely closing the JSDoc.
  return s.replace(/\*\//g, '*\\/')
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true })
  for (const src of SOURCES) {
    const sourcePath = join(SPEC_ROOT, src.tsp)
    const tsp = await readFile(sourcePath, 'utf8')
    const entries = parseEnum(tsp, src.enumName)
    if (entries.length === 0) {
      throw new Error(`${src.tsp}: parsed 0 entries from enum ${src.enumName}`)
    }
    const out = emitTs({ slug: src.slug, enumName: src.enumName, entries })
    const outPath = join(OUT_DIR, `${src.slug}.ts`)
    await writeFile(outPath, out, 'utf8')
    process.stdout.write(`wrote ${outPath} (${entries.length} codes)\n`)
  }
}

main().catch((err) => {
  process.stderr.write(`gen-error-codes failed: ${err.message}\n`)
  process.exit(1)
})
